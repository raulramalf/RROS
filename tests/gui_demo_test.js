// Prueba de la demo (build/gui-demo.html) con servidor simulado. Necesita Playwright y Chromium.
//   PWPATH=<ruta a playwright> node tests/gui_demo_test.js
const { chromium } = require(process.env.PWPATH || 'playwright');
const path = require('path');
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROMIUM || '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
  const errs = [], fails = [];
  const ok = (c, m) => { if (!c) { fails.push(m); console.log('  FALLO:', m); } };
  const p = await b.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'dark' });
  p.on('console', m => { if (m.type() === 'error' && !/ERR_FAILED|fonts/.test(m.text())) errs.push(m.text()); });
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await p.route('**/*', r => r.request().url().startsWith('file:') ? r.continue() : r.abort());
  await p.goto('file://' + path.resolve(__dirname, '..', 'build', 'gui-demo.html'));
  await p.waitForSelector('.themes .tcard');
  ok(await p.locator('.tcard').count() === 7, '7 temas');
  await p.click('.tcard:has-text("dracula")'); await p.waitForTimeout(200);
  ok((await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--bg').trim())) === '#282a36', 'tema dracula pinta la ventana');
  await p.click('.seg button:has-text("Claro")'); await p.waitForTimeout(200);
  ok((await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--bg').trim())) === '#fffbeb', 'variante clara');
  await p.click('#nav button:has-text("Interfaz")');
  const gap = p.locator('[data-key="ui.gap"] input[type=number]');
  await gap.fill('9999'); await gap.dispatchEvent('change'); await p.waitForTimeout(200);
  ok((await p.textContent('#toast')).includes('fuera de rango [0, 64]'), 'el rango se valida igual que en C');
  await gap.fill('30'); await gap.dispatchEvent('change'); await p.waitForTimeout(200);
  ok(await p.locator('[data-key="ui.gap"] .reset:not([hidden])').count() === 1, 'aparece restablecer');
  await p.click('#nav button:has-text("Atajos")');
  await p.fill('input[aria-label="Identificador nuevo"]', 'nav');
  await p.fill('input[aria-label="Valor nuevo"]', 'Mod+Shift+b exec firefox');
  await p.click('button:has-text("Añadir")'); await p.waitForTimeout(300);
  ok(await p.locator('.dyn .id:has-text("nav")').count() === 1, 'atajo añadido');
  await p.fill('input[aria-label="Identificador nuevo"]', 'mal');
  await p.fill('input[aria-label="Valor nuevo"]', 'Mod+x rm -rf /');
  await p.click('button:has-text("Añadir")'); await p.waitForTimeout(300);
  ok(await p.locator('.dyn .id:has-text("mal")').count() === 0, 'atajo peligroso rechazado');
  await p.click('#nav button:has-text("Reglas")');
  await p.click('.chip >> nth=0'); await p.click('button:has-text("Añadir")'); await p.waitForTimeout(300);
  ok(await p.locator('.dyn .id:has-text("ff")').count() === 1, 'regla de ejemplo añadida con un clic');
  await p.click('#nav button:has-text("Copias")');
  await p.fill('input[aria-label="Nombre de la instantánea"]', 'prueba');
  await p.click('button:has-text("Guardar instantánea")'); await p.waitForTimeout(300);
  ok(await p.locator('.dyn .id:has-text("prueba")').count() === 1, 'instantánea guardada');
  await p.click('button:has-text("Mostrar mis ajustes")'); await p.waitForTimeout(200);
  const exp = await p.inputValue('textarea');
  ok(exp.includes('theme = "dracula"') && exp.includes('gap = 30') && exp.includes('[keybind]'), 'exportar refleja los cambios');
  await p.click('#nav button:has-text("Temas y colores")');
  await p.fill('input[aria-label="Nombre del tema nuevo"]', 'mio');
  await p.click('button:has-text("Crear tema")'); await p.waitForTimeout(300);
  ok(await p.locator('.colors').count() === 2, 'editor de colores del tema propio');
  // seguridad, dispositivos y archivos con los datos reales de las herramientas (portátil de ejemplo)
  await p.click('#nav button:has-text("Seguridad")');
  await p.waitForSelector('.check');
  ok(await p.locator('.check').count() >= 10 && /^\d+$/.test((await p.textContent('.score .num')).trim()), 'demo: auditoría de seguridad');
  await p.click('button:has-text("Aplicar estricto")'); await p.waitForTimeout(200);
  ok((await p.textContent('#toast')).includes('contraseña'), 'demo: aplicar un nivel');
  await p.click('#nav button:has-text("Dispositivos")');
  await p.waitForSelector('.dev[data-dev="sdb1"]');
  ok(await p.locator('.dev').count() >= 10, 'demo: inventario de dispositivos');
  await p.click('.dev[data-dev="sdb1"] button:has-text("Desmontar")'); await p.waitForTimeout(200);
  await p.waitForSelector('.dev[data-dev="sdb1"] button:has-text("Montar")');
  ok(true, 'demo: desmontar cambia el estado');
  await p.click('.dev[data-dev="sdb"] button:has-text("Expulsar")'); await p.waitForTimeout(200);
  ok(await p.locator('.dev[data-dev="sdb1"]').count() === 0, 'demo: expulsar quita la memoria');
  await p.click('#nav button:has-text("Crear archivos")');
  await p.waitForSelector('select[aria-label="Plantilla"]');
  await p.selectOption('select[aria-label="Plantilla"]', 'web');
  await p.fill('input[aria-label="Nombre del archivo"]', 'inicio');
  await p.click('button:has-text("Crear y abrir")'); await p.waitForTimeout(200);
  ok((await p.textContent('#toast')).includes('inicio.html'), 'demo: crear un archivo');
  console.log(errs.length ? 'ERRORES JS: ' + errs.join(' | ') : 'sin errores de JavaScript');
  console.log(fails.length ? fails.length + ' fallo(s)' : 'DEMO OK');
  await b.close();
  process.exit(fails.length || errs.length ? 1 : 0);
})();
